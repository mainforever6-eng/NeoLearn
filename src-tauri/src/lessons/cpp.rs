// Курс C++ — 20 уроков.
// Предполагается, что в crate::lessons определены:
//   pub struct Lesson { id, course, title, subtitle, duration, level,
//                       goals: Vec<String>, blocks: Vec<Block>,
//                       practice: Vec<String>, takeaways: Vec<String> }
//   pub enum Block {
//       Code    { title: String, lang: String, code: String },
//       Tip     { title: String, body: String },
//       Warning { title: String, body: String },
//       List    { title: String, items: Vec<String> },
//       Text    { title: String, body: String },
//   }
// Если у вас другие имена полей/вариантов — поправьте только сигнатуру
// хелпера `l()` и конструкторы Block.

use super::{Block, Lesson};

fn l(
    id: u32,
    title: &str,
    subtitle: &str,
    duration: &str,
    level: &str,
    goals: &[&str],
    blocks: Vec<Block>,
    practice: &[&str],
    takeaways: &[&str],
) -> Lesson {
    Lesson {
        id,
        course: "c++".into(),
        title: title.into(),
        subtitle: subtitle.into(),
        duration: duration.into(),
        level: level.into(),
        goals: goals.iter().map(|s| s.to_string()).collect(),
        blocks,
        practice: practice.iter().map(|s| s.to_string()).collect(),
        takeaways: takeaways.iter().map(|s| s.to_string()).collect(),
    }
}

fn text(title: &str, body: &str) -> Block {
    Block::Text {
        title: title.into(),
        body: body.into(),
    }
}
fn code(title: &str, src: &str) -> Block {
    Block::Code {
        title: title.into(),
        lang: "cpp".into(),
        code: src.into(),
    }
}
fn tip(title: &str, body: &str) -> Block {
    Block::Tip {
        title: title.into(),
        body: body.into(),
    }
}
fn warn(title: &str, body: &str) -> Block {
    Block::Warning {
        title: title.into(),
        body: body.into(),
    }
}
#[allow(dead_code)]
fn list(title: &str, items: &[&str]) -> Block {
    Block::List {
        title: title.into(),
        items: items.iter().map(|s| s.to_string()).collect(),
    }
}

