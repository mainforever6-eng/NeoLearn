pub fn lessons_for(course: &str) -> Vec<Lesson> {
    match normalize_course(course) {
        "rust" => rust_lessons(),
        "javascript" => javascript_lessons(),
        "c++" => cpp::lessons(),
        _ => Vec::new(),
    }
}

pub(crate) fn find_lesson(course: &str, id: u32) -> Option<Lesson> {
    lessons_for(course)
        .into_iter()
        .find(|lesson| lesson.id == id)
}

#[cfg(test)]
fn find_lesson_summary(course: &str, id: u32) -> Option<LessonSummary> {
    lessons_for(course)
        .iter()
        .find(|lesson| lesson.id == id)
        .map(LessonSummary::from)
}

