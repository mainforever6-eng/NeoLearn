#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "lowercase")]
pub enum Block {
    Code {
        title: String,
        lang: String,
        code: String,
    },
    Tip {
        title: String,
        body: String,
    },
    Warning {
        title: String,
        body: String,
    },
    List {
        title: String,
        items: Vec<String>,
    },
    Text {
        title: String,
        body: String,
    },
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Lesson {
    pub id: u32,
    pub course: String,
    pub title: String,
    pub subtitle: String,
    pub duration: String,
    pub level: String,
    pub goals: Vec<String>,
    pub blocks: Vec<Block>,
    pub practice: Vec<String>,
    pub takeaways: Vec<String>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct LessonSummary {
    pub id: u32,
    pub course: String,
    pub title: String,
    pub subtitle: String,
    pub duration: String,
    pub level: String,
}

impl From<&Lesson> for LessonSummary {
    fn from(lesson: &Lesson) -> Self {
        Self {
            id: lesson.id,
            course: lesson.course.clone(),
            title: lesson.title.clone(),
            subtitle: lesson.subtitle.clone(),
            duration: lesson.duration.clone(),
            level: lesson.level.clone(),
        }
    }
}

pub(crate) fn normalize_course(course: &str) -> &str {
    match course {
        "cpp" | "c++" => "c++",
        other => other,
    }
}

pub fn course_title(course: &str) -> &'static str {
    match normalize_course(course) {
        "rust" => "Rust",
        "javascript" => "JavaScript",
        "c++" => "C++",
        _ => "Неизвестный курс",
    }
}

