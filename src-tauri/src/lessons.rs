/*  Общие конструкторы уроков и блоков                                */
/* ------------------------------------------------------------------ */
#[allow(clippy::too_many_arguments)]
fn l(
    course: &str,
    id: u32,
    title: &str,
    subtitle: &str,
    duration: &str,
    level: &str,
    goals: &[&str],
    blocks: Vec<Block>,
    practice: &[&str],
    takeaways: &[&str],
) -> Lesson {
    Lesson {
        id,
        course: course.into(),
        title: title.into(),
        subtitle: subtitle.into(),
        duration: duration.into(),
        level: level.into(),
        goals: goals.iter().map(|s| s.to_string()).collect(),
        blocks,
        practice: practice.iter().map(|s| s.to_string()).collect(),
        takeaways: takeaways.iter().map(|s| s.to_string()).collect(),
    }
}

fn text(title: &str, body: &str) -> Block {
    Block::Text {
        title: title.into(),
        body: body.into(),
    }
}

fn code(title: &str, lang: &str, src: &str) -> Block {
    Block::Code {
        title: title.into(),
        lang: lang.into(),
        code: src.into(),
    }
}

fn tip(title: &str, body: &str) -> Block {
    Block::Tip {
        title: title.into(),
        body: body.into(),
    }
}

fn warn(title: &str, body: &str) -> Block {
    Block::Warning {
        title: title.into(),
        body: body.into(),
    }
}

